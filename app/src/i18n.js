export function useT() {
  const lang = useGame((s) => s.lang)
  const t = (key, vars) => {
    let s = STRINGS[lang][key] ?? key
    if (vars && typeof s === 'string') Object.entries(vars).forEach(([k, v]) => { s = s.replace(`{${k}}`, v) })
    return s
  }
  // Picks the right language from a data field like { es: '...', en: '...' }
  const L = (obj) => (obj && typeof obj === 'object' ? obj[lang] ?? obj.es : obj)
  return { t, L, lang }
}
